#include "TPCReco/GrawFrame.h"

#include <algorithm>

namespace graw {
/////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////
Frame::Frame() : values_(kNSamples, 0), mask_((kNSamples + 63) / 64, 0) {}
/////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////
void Frame::clear() {
  std::fill(values_.begin(), values_.end(), 0);
  std::fill(mask_.begin(), mask_.end(), 0);
  nSamples_.fill(0);
}
/////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////
void Frame::setAllPresent() {
  std::fill(mask_.begin(), mask_.end(), ~uint64_t(0));
  nSamples_.fill(kCellsPerChannel);
}
/////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////
void Frame::setSample(unsigned aget, unsigned channel, unsigned cell, uint16_t value) {
  const std::size_t i = sampleIndex(aget, channel, cell);
  uint64_t &word = mask_[i / 64];
  const uint64_t bit = uint64_t(1) << (i % 64);
  if (!(word & bit)) {
    word |= bit;
    ++nSamples_[channelIndex(aget, channel)];
  }
  values_[i] = value;
}
/////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////
} // namespace graw
